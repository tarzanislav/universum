"""Writes installer/context-menu.iss: the UNIVERSUM submenu of the Explorer's context menu (classic, cascading).

Files: Zlučovanie, Hromadné spracovanie (the folder with this file's template), Single spracovanie, Informácie.
Folders: Hromadné spracovanie. Each item starts Universum.exe with a switch; the running UNIVERSUM takes the request.
python3 tools/installer/context_menu.py
"""
from pathlib import Path

EXTENSIONS = [
    ".mkv", ".mka", ".mks", ".mk3d", ".webm", ".mp4", ".m4v", ".m4a", ".mov", ".avi", ".ts", ".m2ts", ".mts",
    ".mpg", ".mpeg", ".vob", ".ogg", ".ogm", ".opus", ".flac", ".ac3", ".eac3", ".dts", ".aac", ".mp3", ".wav",
    ".h264", ".h265", ".hevc", ".srt", ".ass", ".ssa", ".vtt", ".sup", ".idx",
]

FILE_ITEMS = [
    ("1zlucovanie", "Pridať do Zlučovania", "menu-mux.ico", "--zlucovanie"),
    ("2hromadne", "Pridať do Hromadného spracovania", "menu-batch.ico", "--hromadne"),
    ("3single", "Pridať do Single spracovania", "menu-single.ico", "--single"),
    ("4informacie", "Informácie o súbore", "menu-info.ico", "--informacie"),
]

FOLDER_ITEMS = [FILE_ITEMS[1]]


def menu(root_key, items):
    key = root_key + r"\shell\UNIVERSUM"
    lines = [
        # an older single item ("Otvoriť v UNIVERSUM") is replaced by the submenu
        f'Root: HKA; Subkey: "{key}"; Flags: deletekey uninsdeletekey',
        f'Root: HKA; Subkey: "{key}"; ValueType: string; ValueName: "MUIVerb"; ValueData: "UNIVERSUM"',
        f'Root: HKA; Subkey: "{key}"; ValueType: string; ValueName: "Icon"; ValueData: "{{app}}\\{{#AppExe}}"',
        f'Root: HKA; Subkey: "{key}"; ValueType: string; ValueName: "SubCommands"; ValueData: ""',
        # also on the submenu itself: with more than 15 selected files Explorer would hide it otherwise
        f'Root: HKA; Subkey: "{key}"; ValueType: string; ValueName: "MultiSelectModel"; ValueData: "Player"',
    ]
    for name, text, icon, switch in items:
        item = key + "\\shell\\" + name
        lines += [
            f'Root: HKA; Subkey: "{item}"; ValueType: string; ValueName: "MUIVerb"; ValueData: "{text}"',
            f'Root: HKA; Subkey: "{item}"; ValueType: string; ValueName: "Icon"; ValueData: "{{app}}\\Assets\\{icon}"',
            # all selected files at once (not at most 15); UNIVERSUM collects them
            f'Root: HKA; Subkey: "{item}"; ValueType: string; ValueName: "MultiSelectModel"; ValueData: "Player"',
            f'Root: HKA; Subkey: "{item}\\command"; ValueType: string; ValueName: ""; ValueData: """{{app}}\\{{#AppExe}}"" {switch} ""%1"""',
        ]
    return lines


def main():
    lines = [
        "; Generated by tools/installer/context_menu.py – do not edit by hand.",
        "; Explorer context menu: UNIVERSUM > Zlučovanie / Hromadné spracovanie / Single spracovanie / Informácie",
        "; (in Windows 11 under \"Zobraziť ďalšie možnosti\"); removed when uninstalling.",
        "",
    ]
    for extension in EXTENSIONS:
        lines += menu(r"Software\Classes\SystemFileAssociations" + "\\" + extension, FILE_ITEMS)
    lines += menu(r"Software\Classes\Directory", FOLDER_ITEMS)
    target = Path(__file__).resolve().parents[2] / "installer" / "context-menu.iss"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")


if __name__ == "__main__":
    main()
